//! Permanent regression suite for SPIF-PAYLOAD-CROSSDOC-CYCLE-001.
//!
//! Invariant: a cycle among payload Node.refs must fail closed at
//! decode. Both readers exempted refs starting with "spif:" from
//! dangling/cycle checks (SPEC 8.1 cross-document refs) without
//! checking the id against the local node set, so a cycle routed
//! through a LOCAL node whose id starts with "spif:" escaped
//! detection.
//!
//! Fix: a ref is cross-document ONLY when its target id is not
//! among the local node ids (local ids win), in both readers.
//! Genuine external refs (no local node with that id) stay exempt.
//!
//! The legs consume hostile documents generated by the Python
//! implementation (chunk surgery identical to the loop probe of
//! cycle 2026-11-20-1122), located via SPIF_PYTHON the same way
//! tests/alts_nonfinite.rs locates it.
//!
//! NOTE: written without a cargo toolchain on the authoring VM —
//! uncompiled/untested there; first cargo run verifies it.

use anyhow::{anyhow, Result};
use spif_rust::SPIFReader;
use std::path::PathBuf;
use std::process::Command;

fn find_python() -> Result<PathBuf> {
    if let Ok(py) = std::env::var("SPIF_PYTHON") {
        return Ok(PathBuf::from(py));
    }
    for candidate in ["python3", "python", "/usr/bin/python3"] {
        let output = Command::new(candidate)
            .arg("-c")
            .arg("import importlib.util; raise SystemExit(0 if all(importlib.util.find_spec(m) for m in ('cbor2','cryptography')) else 1)")
            .output();
        if let Ok(output) = output {
            if output.status.success() {
                return Ok(PathBuf::from(candidate));
            }
        }
    }
    Err(anyhow!("no Python with cbor2+cryptography; set SPIF_PYTHON"))
}

/// Ask Python to write a document whose PAYLOAD chunk carries the
/// given node graph (chunk surgery on a genuine writer encoding,
/// checksum recomputed). NODES_EXPR is a Python list of
/// (id, refs) pairs.
fn hostile_doc_bytes(nodes_expr: &str, out: &std::path::Path) -> Result<()> {
    let script = r#"
import hashlib, struct, sys, cbor2
from spif import Node, Provenance, SPIFDocument
from spif.format import CHUNK_CHECKSUM, CHUNK_PAYLOAD, MAGIC
from spif.writer import SPIFWriter
_CHUNK = struct.Struct(">BI")
CONF = {"mean": 0.9, "var": 0.05, "shape": "gaussian", "semantics": "epistemic"}
doc = SPIFDocument(
    payload=[Node(id="n1", type="fact", value="canonical fact")],
    provenance=Provenance(source_model="canonical-test", timestamp_ms=1700000000000, nonce="n1"))
data = SPIFWriter().encode(doc)
off = len(MAGIC) + 2; parts = []
while off < len(data):
    ct, ln = _CHUNK.unpack_from(data, off); parts.append((ct, data[off+5:off+5+ln])); off += 5 + ln
    if ct == CHUNK_CHECKSUM: break
nodes = [{"id": nid, "type": "fact", "value": "v", "confidence": dict(CONF), "refs": refs} for nid, refs in NODES_EXPR]
parts = [(ct, cbor2.dumps(nodes) if ct == CHUNK_PAYLOAD else p) for ct, p in parts if ct != CHUNK_CHECKSUM]
body = data[:len(MAGIC)+2] + b"".join(_CHUNK.pack(ct, len(p)) + p for ct, p in parts)
sys.stdout.buffer.write(body + _CHUNK.pack(CHUNK_CHECKSUM, 32) + hashlib.sha256(body).digest())
"#;
    let script = script.replace("NODES_EXPR", nodes_expr);
    let py = find_python()?;
    let repo_py = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../spif-py");
    let output = Command::new(&py)
        .arg("-c")
        .arg(&script)
        .env("PYTHONPATH", &repo_py)
        .output()?;
    if !output.status.success() {
        return Err(anyhow!(
            "python generator failed: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    std::fs::write(out, &output.stdout)?;
    Ok(())
}

#[test]
fn reader_rejects_cycles_via_spif_prefixed_local_nodes() -> Result<()> {
    let dir = std::env::temp_dir();
    for (name, expr) in [
        ("via", "[('spif:x', ['b']), ('b', ['spif:x'])]"),
        ("self", "[('spif:x', ['spif:x'])]"),
        ("both", "[('spif:a', ['spif:b']), ('spif:b', ['spif:a'])]"),
        ("plain", "[('a', ['b']), ('b', ['a'])]"),
    ] {
        let path = dir.join(format!("spif-crossdoc-{name}.spif"));
        hostile_doc_bytes(expr, &path)?;
        let data = std::fs::read(&path)?;
        assert!(
            SPIFReader::new().read(&data).is_err(),
            "reader accepted cycle {expr}"
        );
    }
    // Controls: genuine cross-document ref and an acyclic local
    // graph must decode.
    for (name, expr, want_len) in [
        ("ext", "[('a', ['spif:sha256:deadbeef#n9'])]", 1usize),
        ("acyclic", "[('a', ['b']), ('b', [])]", 2usize),
    ] {
        let path = dir.join(format!("spif-crossdoc-{name}.spif"));
        hostile_doc_bytes(expr, &path)?;
        let data = std::fs::read(&path)?;
        let doc = SPIFReader::new().read(&data)?;
        assert_eq!(doc.payload.len(), want_len);
    }
    Ok(())
}
