//! Permanent regression suite for SPIF-ALTS-NEGATIVE-WEIGHT-001.
//!
//! Invariant: when normalized=true, ALTS weights are probabilities —
//! each must lie in [0, 1], in both readers and both writers. The
//! readers checked finiteness (all weights) and the SUM (1.0 +- 0.01,
//! normalized only) but never the per-weight sign/range, so
//! [-0.5, 1.5] summed to 1.0 and decoded unrejected.
//!
//! Fix: Python reader/writer gained a per-weight [0, 1] range gate
//! for normalized alternatives; the Rust reader and writer gained
//! the same gate. Unnormalized (normalized=false) weights are
//! scores: finite negative or >1 values stay valid.
//!
//! The reader legs consume hostile documents generated by the
//! Python implementation (chunk surgery identical to the loop
//! probe of cycle 2026-11-19-0522), located via SPIF_PYTHON the
//! same way tests/alts_nonfinite.rs locates it.
//!
//! NOTE: written without a cargo toolchain on the authoring VM —
//! uncompiled/untested there; first cargo run verifies it.

use anyhow::{anyhow, Result};
use spif_rust::{Alternative, Distribution, Node, Provenance, SPIFDocument, SPIFReader, SPIFWriter, Value};
use std::path::PathBuf;
use std::process::Command;

fn doc_with_weights(weights: &[f64], normalized: bool) -> SPIFDocument {
    SPIFDocument {
        payload: vec![Node {
            id: "n1".to_string(),
            node_type: "fact".to_string(),
            value: Value::Text("canonical fact".to_string()),
            confidence: Distribution::certain("epistemic"),
            refs: vec![],
        }],
        provenance: Some(Provenance {
            source_model: "canonical-test".to_string(),
            timestamp_ms: 1_700_000_000_000,
            temperature: 0.0,
            input_hash: "".to_string(),
            context_ref: "".to_string(),
            model_version: "".to_string(),
            attempt: 0,
            task_id: "".to_string(),
            model_card: "".to_string(),
            risk_tier: "".to_string(),
        }),
        semantic: None,
        trace: vec![],
        trace_method: "post-hoc".to_string(),
        alternatives: weights
            .iter()
            .enumerate()
            .map(|(i, &w)| Alternative {
                weight: w,
                nodes: vec![Node {
                    id: format!("a{}", i + 1),
                    node_type: "fact".to_string(),
                    value: Value::Text(format!("alt {}", i + 1)),
                    confidence: Distribution::certain("epistemic"),
                    refs: vec![],
                }],
                normalized,
            })
            .collect(),
        delta: None,
        signature: None,
        signatures: vec![],
        task_info: None,
        revocations: Vec::new(),
        timestamp_anchor: None,
    }
}

#[test]
fn writer_rejects_normalized_out_of_range_weights() {
    for weights in [&[-0.5, 1.5][..], &[2.0, -1.0][..], &[-0.1, 0.6, 0.5][..], &[1.5][..]] {
        let doc = doc_with_weights(weights, true);
        assert!(
            SPIFWriter::new().encode(&doc).is_err(),
            "writer accepted normalized weights {weights:?}"
        );
    }
}

#[test]
fn writer_accepts_unnormalized_negative_score_and_roundtrips() {
    let doc = doc_with_weights(&[-2.5], false);
    let data = SPIFWriter::new().encode(&doc).expect("unnormalized score must encode");
    let restored = SPIFReader::new().read(&data).expect("unnormalized score must decode");
    assert_eq!(restored.alternatives[0].weight, -2.5);
}

#[test]
fn writer_accepts_normalized_pair_and_roundtrips() {
    let doc = doc_with_weights(&[0.5, 0.5], true);
    let data = SPIFWriter::new().encode(&doc).expect("valid pair must encode");
    let restored = SPIFReader::new().read(&data).expect("valid pair must decode");
    assert_eq!(restored.alternatives.len(), 2);
}

fn find_python() -> Result<PathBuf> {
    if let Ok(py) = std::env::var("SPIF_PYTHON") {
        return Ok(PathBuf::from(py));
    }
    for candidate in ["python3", "python", "/usr/bin/python3"] {
        let output = Command::new(candidate)
            .arg("-c")
            .arg("import importlib.util; raise SystemExit(0 if all(importlib.util.find_spec(m) for m in ('cbor2','cryptography')) else 1)")
            .output();
        if let Ok(output) = output {
            if output.status.success() {
                return Ok(PathBuf::from(candidate));
            }
        }
    }
    Err(anyhow!("no Python with cbor2+cryptography; set SPIF_PYTHON"))
}

/// Ask Python to write a document whose ALTS chunk carries the
/// given weights under normalized=True (chunk surgery on a genuine
/// writer encoding, checksum recomputed).
fn hostile_doc_bytes(weights_expr: &str, out: &std::path::Path) -> Result<()> {
    let script = r#"
import hashlib, struct, sys, cbor2
from spif import Alternative, Node, Provenance, SPIFDocument
from spif.format import CHUNK_ALTS, CHUNK_CHECKSUM, MAGIC
from spif.writer import SPIFWriter
_CHUNK = struct.Struct(">BI")
def _node(i, v):
    return {"id": f"a{i}", "type": "fact", "value": v, "refs": [], "confidence": cbor2.CBORTag(1000, {"mean": 1.0, "var": 0.0, "shape": "point", "semantics": "epistemic"})}
doc = SPIFDocument(
    payload=[Node(id="n1", type="fact", value="canonical fact")],
    provenance=Provenance(source_model="canonical-test", timestamp_ms=1700000000000, nonce="n1"),
    alternatives=[Alternative(weight=1.0, nodes=[Node(id="a1", type="fact", value="alt fact")], normalized=True)])
data = SPIFWriter().encode(doc)
off = len(MAGIC) + 2; parts = []
while off < len(data):
    ct, ln = _CHUNK.unpack_from(data, off); parts.append((ct, data[off+5:off+5+ln])); off += 5 + ln
    if ct == CHUNK_CHECKSUM: break
weights = WEIGHTS_EXPR
evil = {"normalized": True, "alts": [{"weight": w, "nodes": [_node(i+1, f"alt {i+1}")]} for i, w in enumerate(weights)]}
parts = [(ct, cbor2.dumps(evil) if ct == CHUNK_ALTS else p) for ct, p in parts if ct != CHUNK_CHECKSUM]
body = data[:len(MAGIC)+2] + b"".join(_CHUNK.pack(ct, len(p)) + p for ct, p in parts)
sys.stdout.buffer.write(body + _CHUNK.pack(CHUNK_CHECKSUM, 32) + hashlib.sha256(body).digest())
"#;
    let script = script.replace("WEIGHTS_EXPR", weights_expr);
    let py = find_python()?;
    let repo_py = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../spif-py");
    let output = Command::new(&py)
        .arg("-c")
        .arg(&script)
        .env("PYTHONPATH", &repo_py)
        .output()?;
    if !output.status.success() {
        return Err(anyhow!(
            "python generator failed: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    std::fs::write(out, &output.stdout)?;
    Ok(())
}

#[test]
fn reader_rejects_normalized_negative_weights_from_python_bytes() -> Result<()> {
    let dir = std::env::temp_dir();
    for (name, expr) in [
        ("neg-over", "[-0.5, 1.5]"),
        ("over-neg", "[2.0, -1.0]"),
        ("small-neg", "[-0.1, 0.6, 0.5]"),
    ] {
        let path = dir.join(format!("spif-alts-neg-{name}.spif"));
        hostile_doc_bytes(expr, &path)?;
        let data = std::fs::read(&path)?;
        assert!(
            SPIFReader::new().read(&data).is_err(),
            "reader accepted normalized weights {expr}"
        );
    }
    // Control through the same surgery must decode.
    let path = dir.join("spif-alts-neg-control.spif");
    hostile_doc_bytes("[0.5, 0.5]", &path)?;
    let data = std::fs::read(&path)?;
    let doc = SPIFReader::new().read(&data)?;
    assert_eq!(doc.alternatives.len(), 2);
    Ok(())
}
