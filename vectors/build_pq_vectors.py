#!/usr/bin/env python3
"""
Builder for the PQ hybrid conformance cases (SPIF v1.4, SPEC §7.9).

Appends cases 12-15 (hybrid ``ed25519+ml-dsa-65``) to the kit's
manifest.json. The v1.3 builder (build_vectors.py) owns cases 01-11 and
is untouched; this script replaces only its own cases, so the two
builders can run in either order.

Determinism note: unlike cases 01-11, hybrid artifacts are NOT
byte-identical across builds. FIPS 204 hedged signing is randomized and
ML-DSA key generation here is fresh per build. What is deterministic is
the *expected outcome* of every case, which is all the runner asserts.
All keys are TEST-ONLY, generated by this script and never reused —
never sign a real artifact with them.

Usage:  python build_pq_vectors.py
Requires: the spif package plus the `pqcrypto` backend (the 'pq' extra).
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "spif-py"))

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from spif import Node, Provenance, SPIFDocument, SPIFReader, SPIFWriter
from spif.crypto import sign_document
from spif.pq_hybrid import (
    HYBRID_ALGORITHM,
    generate_ml_dsa_65_keypair,
    sign_document_hybrid,
)
from spif.types import Signature

HERE = Path(__file__).resolve().parent
ART = HERE / "artifacts"
TS0 = 1_700_000_000_000
PQ_CASE_IDS = {"12", "13", "14", "15"}


def _test_ed_key(label: str) -> Ed25519PrivateKey:
    seed = hashlib.sha256(f"spif-v13-conformance-test-key:{label}".encode()).digest()
    return Ed25519PrivateKey.from_private_bytes(seed)


def _doc(text: str) -> SPIFDocument:
    return SPIFDocument(
        payload=[Node(id="n1", type="fact", value=text)],
        provenance=Provenance(source_model="conformance-model", timestamp_ms=TS0),
    )


def _mutate_signature(data: bytes, mutate) -> bytes:
    doc = SPIFReader().decode(data)
    doc.signature = Signature(
        algorithm=doc.signature.algorithm,
        signer=doc.signature.signer,
        signature=mutate(doc.signature.signature),
    )
    return SPIFWriter().encode(doc)


def _flip(sig: bytes, offset: int) -> bytes:
    b = bytearray(sig)
    b[offset] ^= 0x01
    return bytes(b)


def _expected(trust: str, sig: str) -> dict:
    return {
        "trust_status": trust,
        "signature_status": sig,
        "timestamp_status": "absent",
        "forged_revocations": 0,
        "references": [],
    }


def main() -> None:
    ART.mkdir(exist_ok=True)
    ed_key = _test_ed_key("signer")
    ml_pk, ml_sk = generate_ml_dsa_65_keypair()

    valid = sign_document_hybrid(_doc("hybrid conformance fact"), ed_key, ml_sk, ml_pk)
    (ART / "12_hybrid_valid.spif").write_bytes(valid)

    tampered_ml = _mutate_signature(valid, lambda s: _flip(s, 64 + 1000))
    (ART / "13_hybrid_tampered_ml_dsa.spif").write_bytes(tampered_ml)

    tampered_ed = _mutate_signature(valid, lambda s: _flip(s, 10))
    (ART / "14_hybrid_tampered_ed25519.spif").write_bytes(tampered_ed)

    ed_only = sign_document(_doc("hybrid conformance fact"), ed_key)
    doc = SPIFReader().decode(ed_only)
    doc.signature = Signature(
        algorithm=HYBRID_ALGORITHM,
        signer=doc.signature.signer,
        signature=doc.signature.signature,
    )
    (ART / "15_hybrid_ed25519_only_relabelled.spif").write_bytes(
        SPIFWriter().encode(doc)
    )

    cases = [
        {
            "id": "12",
            "name": "hybrid_valid",
            "description": "Hybrid ed25519+ml-dsa-65 signed artifact (SPEC 7.9). "
                           "Strict hybrid verification (require_pq gate mode): "
                           "both components valid -> VALID. Executed by the "
                           "pq_hybrid adapter (spif.trust, require_pq).",
            "artifact": "artifacts/12_hybrid_valid.spif",
            "adapter": "pq_hybrid",
            "inputs": {},
            "expected": _expected("VALID", "valid"),
        },
        {
            "id": "13",
            "name": "hybrid_tampered_ml_dsa",
            "description": "ML-DSA-65 component byte flipped, checksum repaired. "
                           "Hybrid verification requires BOTH components -> INVALID.",
            "artifact": "artifacts/13_hybrid_tampered_ml_dsa.spif",
            "adapter": "pq_hybrid",
            "inputs": {},
            "expected": _expected("INVALID", "invalid"),
        },
        {
            "id": "14",
            "name": "hybrid_tampered_ed25519",
            "description": "ed25519 component byte flipped, checksum repaired. "
                           "Hybrid verification requires BOTH components -> INVALID.",
            "artifact": "artifacts/14_hybrid_tampered_ed25519.spif",
            "adapter": "pq_hybrid",
            "inputs": {},
            "expected": _expected("INVALID", "invalid"),
        },
        {
            "id": "15",
            "name": "hybrid_ed25519_only_relabelled",
            "description": "ed25519-only signature with the algorithm field relabelled "
                           "to ed25519+ml-dsa-65 (64-byte signature, no ML-DSA component). "
                           "The hybrid verifier must reject it -> INVALID.",
            "artifact": "artifacts/15_hybrid_ed25519_only_relabelled.spif",
            "adapter": "pq_hybrid",
            "inputs": {},
            "expected": _expected("INVALID", "invalid"),
        },
    ]

    manifest_path = HERE / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    kept = [c for c in manifest["cases"] if c["id"] not in PQ_CASE_IDS]
    manifest["cases"] = kept + cases
    manifest_path.write_text(json.dumps(manifest, indent=2))
    print(f"built {len(cases)} PQ hybrid cases -> {ART}, manifest.json updated")


if __name__ == "__main__":
    main()
