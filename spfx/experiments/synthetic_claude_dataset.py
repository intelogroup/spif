"""
Synthetic Claude dataset: 200 SIF-structured QA items generated by Claude.

Each item has:
  - question + graded answer (correct/partial/incorrect)
  - factual_accuracy confidence distribution
  - 3-step reasoning trace (evidence → inference → conclusion)
  - 1 alternative hypothesis
  - full SIF roundtrip validation

Also generates 20 adversarial items: deliberately wrong answers with high confidence,
for stress-testing the LLM-as-judge.

Fully resumable: existing .jsonl lines are skipped on restart.

Usage:
    python experiments/synthetic_claude_dataset.py
    python experiments/synthetic_claude_dataset.py --domains science,math --n 10
"""
from __future__ import annotations
import argparse
import base64
import json
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

import anthropic

from sif import (
    SIFDocument, Node, TraceStep, Alternative, Provenance, Distribution,
    SIFWriter, SIFReader,
)

MODEL = "claude-sonnet-4-6"
DOMAINS = ["science", "math", "history", "law", "medicine"]
ITEMS_PER_DOMAIN = 40
N_ADVERSARIAL_PER_DOMAIN = 4

EXPERIMENTS_DIR = Path(__file__).parent
OUTPUT_JSONL = EXPERIMENTS_DIR / "synthetic_claude_dataset.jsonl"
ADVERSARIAL_JSONL = EXPERIMENTS_DIR / "synthetic_claude_adversarial.jsonl"
MANIFEST_JSON = EXPERIMENTS_DIR / "synthetic_claude_dataset_manifest.json"

GENERATION_PROMPT = """\
Generate a SIF-structured QA item for domain: {domain}

Respond ONLY with a valid JSON object in this EXACT format — no preamble, no markdown:
{{
  "question": "...",
  "answer": "...",
  "answer_grade": "correct",
  "confidence_mean": 0.85,
  "confidence_var": 0.03,
  "trace_steps": [
    {{"id": "s0", "type": "evidence",   "content": "...", "confidence_mean": 0.90, "deps": []}},
    {{"id": "s1", "type": "inference",  "content": "...", "confidence_mean": 0.85, "deps": ["s0"]}},
    {{"id": "s2", "type": "conclusion", "content": "...", "confidence_mean": 0.85, "deps": ["s1"]}}
  ],
  "alternative": {{
    "answer": "...",
    "weight": 0.15
  }}
}}

Requirements:
- question must be non-trivial and domain-appropriate (not a simple fact lookup)
- answer_grade must be "correct", "partial", or "incorrect"
- confidence_mean must honestly reflect answer quality (high if correct, moderate if partial, low if incorrect)
- trace_steps must be causally valid (each step content builds on prior steps)
- alternative.answer must be a plausible but wrong answer
- alternative.weight must be in [0.05, 0.40]
- all values must be JSON-serializable
- Respond ONLY with the JSON object"""

ADVERSARIAL_PROMPT = """\
Generate a SIF-structured QA item for domain: {domain} where the answer is FACTUALLY WRONG
but stated with high confidence. This is for stress-testing a calibration judge system.

Respond ONLY with a valid JSON object in this EXACT format — no preamble, no markdown:
{{
  "question": "...",
  "answer": "...(this answer is factually INCORRECT)...",
  "answer_grade": "incorrect",
  "confidence_mean": 0.92,
  "confidence_var": 0.02,
  "trace_steps": [
    {{"id": "s0", "type": "evidence",   "content": "...", "confidence_mean": 0.95, "deps": []}},
    {{"id": "s1", "type": "inference",  "content": "...", "confidence_mean": 0.93, "deps": ["s0"]}},
    {{"id": "s2", "type": "conclusion", "content": "...", "confidence_mean": 0.92, "deps": ["s1"]}}
  ],
  "alternative": {{
    "answer": "...(this is actually the correct answer)...",
    "weight": 0.05
  }}
}}

Requirements:
- The answer field must be factually INCORRECT
- confidence_mean must be HIGH (0.85–0.99) despite being wrong — that's the whole point
- The alternative.answer must be the actual correct answer
- alternative.weight must be LOW (0.02–0.10)
- Respond ONLY with the JSON object"""


# ---------------------------------------------------------------------------
# Resumability helpers
# ---------------------------------------------------------------------------

def load_existing_items(path: Path) -> list[dict]:
    """Read existing .jsonl, return list of already-generated items."""
    if not path.exists():
        return []
    items = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            try:
                items.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    return items


def append_item(path: Path, item: dict) -> None:
    """Append one item to a .jsonl file."""
    with open(path, "a", encoding="utf-8") as f:
        f.write(json.dumps(item) + "\n")


# ---------------------------------------------------------------------------
# Generation
# ---------------------------------------------------------------------------

def _parse_item(text: str) -> dict | None:
    """Extract and parse the JSON object from Claude's response."""
    # Strip markdown fences if present
    text = text.strip()
    if text.startswith("```"):
        text = text.split("```", 2)[1]
        if text.startswith("json"):
            text = text[4:]
        text = text.strip()
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        # Try to find the first {...} block
        start = text.find("{")
        end = text.rfind("}") + 1
        if start >= 0 and end > start:
            try:
                return json.loads(text[start:end])
            except json.JSONDecodeError:
                pass
    return None


def _validate_item(item: dict) -> bool:
    """Basic schema validation."""
    required = ["question", "answer", "answer_grade", "confidence_mean",
                "confidence_var", "trace_steps", "alternative"]
    for field in required:
        if field not in item:
            return False
    if not isinstance(item["trace_steps"], list) or len(item["trace_steps"]) != 3:
        return False
    if not isinstance(item["alternative"], dict):
        return False
    try:
        mean = float(item["confidence_mean"])
        var = float(item["confidence_var"])
        if not (0.0 <= mean <= 1.0 and var >= 0.0):
            return False
    except (TypeError, ValueError):
        return False
    return True


def generate_qa_item(
    client: anthropic.Anthropic,
    domain: str,
    item_idx: int,
    adversarial: bool = False,
) -> dict | None:
    """Call Claude to generate one QA item. Retries up to 2 times on parse failure."""
    prompt_template = ADVERSARIAL_PROMPT if adversarial else GENERATION_PROMPT
    prompt = prompt_template.format(domain=domain)

    for attempt in range(3):
        try:
            msg = client.messages.create(
                model=MODEL,
                max_tokens=800,
                messages=[{"role": "user", "content": prompt}],
            )
            text = msg.content[0].text
            item = _parse_item(text)
            if item and _validate_item(item):
                return item
            if attempt < 2:
                time.sleep(1.0)
        except Exception as e:
            print(f"    API error (attempt {attempt+1}): {e}", file=sys.stderr)
            time.sleep(2.0)
    return None


# ---------------------------------------------------------------------------
# SIF construction
# ---------------------------------------------------------------------------

def build_sif_from_item(item: dict, domain: str, item_id: str) -> SIFDocument:
    """Construct and round-trip-validate a SIFDocument from a generated item."""
    ts = int(time.time() * 1000)

    payload = [Node(
        id=item_id,
        type="qa_answer",
        value=item["answer"],
        confidence=Distribution(
            mean=float(item["confidence_mean"]),
            var=float(item["confidence_var"]),
            shape="gaussian",
            semantics="factual_accuracy",
        ),
    )]

    trace = []
    for step_def in item["trace_steps"]:
        trace.append(TraceStep(
            id=step_def["id"],
            type=step_def["type"],
            content=step_def["content"],
            confidence=Distribution(
                mean=float(step_def.get("confidence_mean", 0.8)),
                var=0.03,
                shape="gaussian",
                semantics="epistemic",
            ),
            deps=step_def.get("deps", []),
        ))

    alt_def = item["alternative"]
    alt_weight = float(alt_def.get("weight", 0.15))
    alternatives = [
        Alternative(
            weight=round(1.0 - alt_weight, 3),
            nodes=[Node(
                id=f"{item_id}_main",
                type="qa_answer",
                value=item["answer"],
                confidence=Distribution(
                    mean=float(item["confidence_mean"]),
                    var=float(item["confidence_var"]),
                    shape="gaussian",
                    semantics="factual_accuracy",
                ),
            )],
            normalized=False,
        ),
        Alternative(
            weight=alt_weight,
            nodes=[Node(
                id=f"{item_id}_alt",
                type="qa_answer",
                value=alt_def.get("answer", ""),
                confidence=Distribution(
                    mean=max(0.05, 1.0 - float(item["confidence_mean"])),
                    var=0.05,
                    shape="gaussian",
                    semantics="factual_accuracy",
                ),
            )],
            normalized=False,
        ),
    ]

    doc = SIFDocument(
        payload=payload,
        trace=trace,
        trace_method="post-hoc",
        alternatives=alternatives,
        provenance=Provenance(
            source_model=MODEL,
            timestamp_ms=ts,
        ),
    )

    # Validate round-trip
    writer = SIFWriter()
    reader = SIFReader()
    raw = writer.encode(doc)
    reader.decode(raw)  # raises on any format error

    return doc


def encode_item_for_jsonl(
    item: dict,
    sif_doc: SIFDocument,
    domain: str,
    item_id: str,
) -> dict:
    """Encode one item for a JSONL line."""
    raw = SIFWriter().encode(sif_doc)
    return {
        "id": item_id,
        "domain": domain,
        "question": item["question"],
        "answer": item["answer"],
        "answer_grade": item["answer_grade"],
        "confidence_mean": float(item["confidence_mean"]),
        "sif_b64": base64.b64encode(raw).decode("ascii"),
        "timestamp_ms": int(time.time() * 1000),
    }


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(description="Synthetic Claude SIF dataset generator")
    parser.add_argument(
        "--domains",
        default=",".join(DOMAINS),
        help="Comma-separated domains",
    )
    parser.add_argument("--n", type=int, default=ITEMS_PER_DOMAIN,
                        help="Items per domain")
    args = parser.parse_args()

    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        print("ERROR: ANTHROPIC_API_KEY not set", file=sys.stderr)
        sys.exit(1)

    domains = [d.strip() for d in args.domains.split(",") if d.strip()]
    n_per_domain = args.n
    n_adversarial = N_ADVERSARIAL_PER_DOMAIN

    client = anthropic.Anthropic(api_key=api_key)

    # Load existing items for resumability
    existing_normal = {item["id"] for item in load_existing_items(OUTPUT_JSONL)}
    existing_adversarial = {item["id"] for item in load_existing_items(ADVERSARIAL_JSONL)}

    total_target = len(domains) * n_per_domain
    adv_target = len(domains) * n_adversarial
    print(f"Target: {total_target} normal + {adv_target} adversarial items")
    print(f"Already done: {len(existing_normal)} normal, {len(existing_adversarial)} adversarial")

    generated_normal = 0
    generated_adversarial = 0
    all_round_trippable = True

    # --- Normal items ---
    for domain in domains:
        print(f"\n=== {domain} ===")
        for i in range(n_per_domain):
            item_id = f"{domain}_{i:03d}"
            if item_id in existing_normal:
                print(f"  skip {item_id} (already done)")
                continue

            print(f"  generating {item_id}...", end=" ", flush=True)
            item = generate_qa_item(client, domain, i, adversarial=False)
            if item is None:
                print("FAILED — skipping")
                continue

            try:
                sif_doc = build_sif_from_item(item, domain, item_id)
                jsonl_item = encode_item_for_jsonl(item, sif_doc, domain, item_id)
                append_item(OUTPUT_JSONL, jsonl_item)
                generated_normal += 1
                print(f"OK (grade={item['answer_grade']}, conf={item['confidence_mean']:.2f})")
            except Exception as e:
                print(f"SIF ERROR: {e}")
                all_round_trippable = False

            time.sleep(0.1)

    # --- Adversarial items ---
    print("\n=== Adversarial items ===")
    for domain in domains:
        for i in range(n_adversarial):
            item_id = f"adv_{domain}_{i:02d}"
            if item_id in existing_adversarial:
                print(f"  skip {item_id}")
                continue

            print(f"  generating {item_id}...", end=" ", flush=True)
            item = generate_qa_item(client, domain, i, adversarial=True)
            if item is None:
                print("FAILED — skipping")
                continue

            try:
                sif_doc = build_sif_from_item(item, domain, item_id)
                jsonl_item = encode_item_for_jsonl(item, sif_doc, domain, item_id)
                append_item(ADVERSARIAL_JSONL, jsonl_item)
                generated_adversarial += 1
                print(f"OK (conf={item['confidence_mean']:.2f}, WRONG)")
            except Exception as e:
                print(f"SIF ERROR: {e}")
                all_round_trippable = False

            time.sleep(0.1)

    # Write manifest
    final_normal = len(load_existing_items(OUTPUT_JSONL))
    final_adversarial = len(load_existing_items(ADVERSARIAL_JSONL))
    manifest = {
        "model": MODEL,
        "timestamp_ms": int(time.time() * 1000),
        "domains": domains,
        "n_per_domain": n_per_domain,
        "n_items": final_normal,
        "n_adversarial": final_adversarial,
        "all_round_trippable": all_round_trippable,
        "output_jsonl": str(OUTPUT_JSONL),
        "adversarial_jsonl": str(ADVERSARIAL_JSONL),
    }
    MANIFEST_JSON.write_text(json.dumps(manifest, indent=2))

    print(f"\nDone. {final_normal} normal + {final_adversarial} adversarial items.")
    print(f"Manifest: {MANIFEST_JSON}")


if __name__ == "__main__":
    main()
